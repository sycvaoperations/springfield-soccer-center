#!/usr/bin/env node
/**
 * generate-programs-seo.js
 *
 * Reads content/programs.json and injects a visible, crawlable HTML section
 * into index.html between:
 *   <!-- PROGRAMS_SEO_START -->  ...  <!-- PROGRAMS_SEO_END -->
 *
 * Run: node scripts/generate-programs-seo.js
 * Called by: .github/workflows/build-programs.yml after programs.json is built.
 *
 * programs.json shape: { "programs": [ { id, title, cat, status, age, desc, ... } ] }
 */
'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT         = path.join(__dirname, '..');
const PROGRAMS_SRC = path.join(ROOT, 'content', 'programs.json');
const INDEX_HTML   = path.join(ROOT, 'index.html');
const SITE_URL     = 'https://www.springfieldsoccercenter.com';
const ORG_NAME     = 'Springfield Soccer Center';

if (!fs.existsSync(PROGRAMS_SRC)) {
  console.error('ERROR: content/programs.json not found.');
  process.exit(1);
}

const raw      = JSON.parse(fs.readFileSync(PROGRAMS_SRC, 'utf8'));
// Handle both flat array and { programs: [] } wrapper
const programs = Array.isArray(raw) ? raw : (raw.programs || []);

if (!programs.length) {
  console.warn('WARNING: no programs found — SEO section will be empty.');
}

// ── Helpers ──────────────────────────────────────────────────────────────────
function esc(str) {
  return String(str || '')
    .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')
    .replace(/"/g,'&quot;').replace(/'/g,'&#39;');
}

const STATUS_LABELS = {
  open:        'Enrolling Now',
  coming_soon: 'Coming Soon',
  full:        'Full — Join Waitlist',
  waitlist:    'Join Waitlist',
};

const CAT_LABELS = {
  camp:       'Soccer Camp',
  goalkeeper: 'Goalkeeper Training',
  futsal:     'Futsal Clinic',
  academy:    'Player Academy',
  clinic:     'Skills Clinic',
  travel:     'Travel / Elite Training',
  supplement: 'Supplemental Training',
};

function catLabel(cat) {
  return CAT_LABELS[(cat||'').toLowerCase()] ||
    (cat ? cat.charAt(0).toUpperCase() + cat.slice(1) : 'Soccer Program');
}

// ── Schema per program ────────────────────────────────────────────────────────
function buildSchema(p) {
  return JSON.stringify({
    '@context': 'https://schema.org',
    '@type':    'Course',
    name:        p.title || p.name || p.id,
    description: p.desc  || p.description || `${p.title || p.name} at ${ORG_NAME} in Springfield, VA.`,
    url:         `${SITE_URL}/#programs`,
    provider: {
      '@type': 'SportsOrganization',
      name:    ORG_NAME,
      url:     SITE_URL,
      address: {
        '@type':         'PostalAddress',
        streetAddress:   '8704 Morrissette Dr',
        addressLocality: 'Springfield',
        addressRegion:   'VA',
        postalCode:      '22152',
        addressCountry:  'US',
      },
    },
    courseMode:       'onsite',
    educationalLevel: p.age || p.age_group || '',
    inLanguage:       'en',
    keywords: [
      'soccer', catLabel(p.cat || p.category),
      p.age || p.age_group ? `ages ${p.age || p.age_group}` : '',
      'Springfield VA', 'Northern Virginia', 'youth soccer',
    ].filter(Boolean).join(', '),
  }, null, 2);
}

// ── Article per program ───────────────────────────────────────────────────────
function buildArticle(p) {
  const name       = esc(p.title || p.name || p.id);
  const status     = esc(STATUS_LABELS[p.status] || p.status || '');
  const cat        = esc(catLabel(p.cat || p.category));
  const age        = p.age || p.age_group;
  const desc       = esc(p.desc || p.description || '');

  return `
    <article class="ssc-prog" data-program-id="${esc(p.id)}" data-status="${esc(p.status || '')}">
      <script type="application/ld+json">
${buildSchema(p)}
      </script>
      <h3>${name}</h3>
      <p class="ssc-prog-meta">
        <span>${cat}</span>${age ? ` · <span>Ages ${esc(age)}</span>` : ''}${status ? ` · <span>${status}</span>` : ''}
      </p>${desc ? `\n      <p>${desc}</p>` : ''}
    </article>`;
}

// ── Assemble section ──────────────────────────────────────────────────────────
const START = '<!-- PROGRAMS_SEO_START -->';
const END   = '<!-- PROGRAMS_SEO_END -->';

const section = `${START}
<!--
  AUTO-GENERATED by scripts/generate-programs-seo.js — DO NOT EDIT BY HAND.
  Source: content/programs.json. Rebuilt automatically on every push to main.
  Visible at mobile widths (no interactive grid); hidden on desktop via CSS.
  Purpose: crawlable headings + JSON-LD Course schema so program content is indexed.
-->
<section id="programs-index" class="ssc-programs-index" aria-label="All Programs at Springfield Soccer Center">
  <h2>Youth Soccer Programs in Springfield, VA</h2>
  <p>Springfield Soccer Center offers year-round indoor soccer training for youth players
  in Springfield, Fairfax County, and Northern Virginia — including goalkeeper training,
  futsal clinics, player academies, soccer camps, supplemental skills, and indoor turf rentals.</p>
${programs.map(buildArticle).join('\n')}
</section>
${END}`;

// ── Inject ────────────────────────────────────────────────────────────────────
if (!fs.existsSync(INDEX_HTML)) {
  console.error('ERROR: index.html not found.');
  process.exit(1);
}

let html  = fs.readFileSync(INDEX_HTML, 'utf8');
const si  = html.indexOf(START);
const ei  = html.indexOf(END);

if (si !== -1 && ei !== -1) {
  html = html.slice(0, si) + section + html.slice(ei + END.length);
  console.log(`✓ SEO section replaced (${programs.length} programs).`);
} else {
  html = html.replace('</body>', `\n${section}\n</body>`);
  console.log(`✓ SEO section inserted for first time (${programs.length} programs).`);
}

fs.writeFileSync(INDEX_HTML, html, 'utf8');
console.log(`  Done — index.html updated at ${new Date().toISOString()}`);
